"""Repository interfaces shared by ``repositories/postgres`` and ``repositories/mock``.

Both backends are plain modules exposing these functions; ``DATA_BACKEND`` picks
one at import time (see ``__init__.py``). The protocols document the contract,
type the ``users`` / ``workspace`` handles, and ``tests/test_repositories.py``
checks that both modules implement every function with the same parameters.
Rows are plain dicts; ``conn`` is a psycopg connection (``None`` for mock).
"""

from __future__ import annotations

from datetime import datetime, timedelta
from typing import Any, Protocol

Row = dict[str, Any]
Conn = Any



class UsersRepository(Protocol):
    def public_user(self, row: dict[str, Any]) -> dict[str, Any]: ...
    def get_by_email(self, conn: Conn, email: str) -> dict[str, Any] | None: ...
    def get_by_id(self, conn: Conn, user_id: str) -> dict[str, Any] | None: ...
    def create(self, conn: Conn, *, email: str, password_hash: str, name: str, title: str | None) -> dict[str, Any]: ...
    def update(self, conn: Conn, user_id: str, values: dict[str, Any]) -> dict[str, Any] | None: ...
    def create_session(self, conn: Conn, user_id: str, ttl_days: int) -> str: ...
    def get_user_by_session(self, conn: Conn, token: str) -> dict[str, Any] | None: ...
    def delete_session(self, conn: Conn, token: str) -> None: ...
    def delete_all_sessions(self, conn: Conn, user_id: str) -> None: ...
    def issue_token(self, conn: Conn, user_id: str, purpose: str, ttl: timedelta) -> str: ...
    def consume_token(self, conn: Conn, token: str, purpose: str) -> str | None: ...
    def purge_expired(self, conn: Conn) -> dict[str, int]: ...
    def users_due_weekly_review_reminder(self, conn: Conn, week_start: datetime) -> list[dict[str, Any]]: ...
    def claim_delivery(self, conn: Conn, user_id: str, kind: str, ref: str) -> bool: ...
    def release_delivery(self, conn: Conn, user_id: str, kind: str, ref: str) -> None: ...


class WorkspaceRepository(Protocol):
    def list_challenges(self, conn: Conn, user_id: str) -> list[Row]: ...
    def get_challenge(self, conn: Conn, user_id: str, challenge_id: str) -> Row | None: ...
    def create_challenge(self, conn: Conn, user_id: str, values: Row) -> Row: ...
    def update_challenge(self, conn: Conn, user_id: str, challenge_id: str, values: Row) -> Row | None: ...
    def delete_challenge(self, conn: Conn, user_id: str, challenge_id: str) -> bool: ...
    def list_priorities(self, conn: Conn, user_id: str, target_week: str | None = None) -> list[Row]: ...
    def get_priority(self, conn: Conn, user_id: str, priority_id: str) -> Row | None: ...
    def count_active_priorities(self, conn: Conn, user_id: str, target_week: str, exclude_id: str | None = None) -> int: ...
    def create_priority(self, conn: Conn, user_id: str, values: Row) -> Row: ...
    def update_priority(self, conn: Conn, user_id: str, priority_id: str, values: Row) -> Row | None: ...
    def delete_priority(self, conn: Conn, user_id: str, priority_id: str) -> bool: ...
    def list_interests(self, conn: Conn, user_id: str) -> list[Row]: ...
    def create_interest(self, conn: Conn, user_id: str, values: Row) -> Row: ...
    def update_interest(self, conn: Conn, user_id: str, interest_id: str, values: Row) -> Row | None: ...
    def delete_interest(self, conn: Conn, user_id: str, interest_id: str) -> bool: ...
    def list_stakeholders(self, conn: Conn, user_id: str) -> list[Row]: ...
    def get_stakeholder(self, conn: Conn, user_id: str, stakeholder_id: str) -> Row | None: ...
    def create_stakeholder(self, conn: Conn, user_id: str, values: Row) -> Row: ...
    def update_stakeholder(self, conn: Conn, user_id: str, stakeholder_id: str, values: Row) -> Row | None: ...
    def delete_stakeholder(self, conn: Conn, user_id: str, stakeholder_id: str) -> bool: ...
    def get_stakeholder_interest(self, conn: Conn, user_id: str, interest_id: str) -> Row | None: ...
    def create_stakeholder_interest(self, conn: Conn, user_id: str, stakeholder_id: str, values: Row) -> Row: ...
    def update_stakeholder_interest(self, conn: Conn, user_id: str, interest_id: str, values: Row) -> Row | None: ...
    def delete_stakeholder_interest(self, conn: Conn, user_id: str, interest_id: str) -> bool: ...
    def list_reviews(self, conn: Conn, user_id: str, limit: int | None = None) -> list[Row]: ...
    def create_review(self, conn: Conn, user_id: str, values: Row) -> Row: ...
    def list_decision_logs(self, conn: Conn, user_id: str) -> list[Row]: ...
    def create_decision_log(self, conn: Conn, user_id: str, values: Row) -> Row: ...
    def delete_decision_log(self, conn: Conn, user_id: str, log_id: str) -> bool: ...
    def list_memos(self, conn: Conn, user_id: str, memo_ids: list[str] | None = None) -> list[Row]: ...
    def get_memo(self, conn: Conn, user_id: str, memo_id: str) -> Row | None: ...
    def create_memo(self, conn: Conn, user_id: str, values: Row) -> Row: ...
    def update_memo(self, conn: Conn, user_id: str, memo_id: str, values: Row) -> Row | None: ...
    def delete_memo(self, conn: Conn, user_id: str, memo_id: str) -> bool: ...
